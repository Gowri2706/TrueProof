"""
report.py
---------
Generates a clean PDF report for a scan result, matching the fields on the
"Report PDF" screen from the UI spec: Transaction ID, Amount, UPI, Prediction,
Confidence, Date, Reasons, Generated by TrueProof.
"""

import os
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image as RLImage
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

VERDICT_COLORS = {
    "FAKE": colors.HexColor("#EF4B4B"),
    "SUSPICIOUS": colors.HexColor("#F0A020"),
    "GENUINE": colors.HexColor("#1FAA59"),
}


def generate_pdf_report(result: dict, screenshot_path: str, output_path: str):
    """
    result: the dict returned by model/predict.py's full_predict()
    screenshot_path: path to the original uploaded image (embedded in PDF)
    output_path: where to save the generated PDF
    """
    doc = SimpleDocTemplate(output_path, pagesize=A4,
                             topMargin=20 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('title', parent=styles['Heading1'], textColor=colors.HexColor("#3557FF"))
    verdict_style = ParagraphStyle('verdict', parent=styles['Heading1'],
                                    textColor=VERDICT_COLORS.get(result["verdict"], colors.black),
                                    fontSize=22)

    elements = []
    elements.append(Paragraph("TrueProof — Fraud Detection Report", title_style))
    elements.append(Spacer(1, 6))
    elements.append(Paragraph(f"Generated: {datetime.now().strftime('%d %b %Y, %I:%M %p')}", styles['Normal']))
    elements.append(Spacer(1, 14))

    elements.append(Paragraph(f"PREDICTION: {result['verdict']}", verdict_style))
    elements.append(Paragraph(f"Confidence: {result['confidence_percent']}%", styles['Normal']))
    elements.append(Spacer(1, 10))

    if screenshot_path and os.path.exists(screenshot_path):
        elements.append(RLImage(screenshot_path, width=90 * mm, height=160 * mm, kind='proportional'))
        elements.append(Spacer(1, 10))

    ocr = result.get("ocr", {})
    data = [
        ["Field", "Value"],
        ["Transaction ID", ocr.get("transaction_id") or "Not detected"],
        ["Amount", f"₹{ocr.get('amount')}" if ocr.get('amount') else "Not detected"],
        ["UPI ID", ocr.get("upi_id") or "Not detected"],
        ["Status text", ocr.get("status") or "Not detected"],
        ["Date on screenshot", ocr.get("date") or "Not detected"],
        ["ELA tampering score", f"{result.get('ela_score')}/100"],
        ["CNN genuine probability", f"{result.get('cnn_genuine_probability')}"],
    ]
    table = Table(data, colWidths=[60 * mm, 90 * mm])
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#3557FF")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#DDDDDD")),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F6FC")]),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(table)
    elements.append(Spacer(1, 14))

    elements.append(Paragraph("Reasons / Evidence", styles['Heading3']))
    for r in result.get("reasons", []):
        elements.append(Paragraph(f"• {r}", styles['Normal']))

    elements.append(Spacer(1, 20))
    elements.append(Paragraph("Generated by TrueProof — for verification support only. "
                               "Always confirm large payments via your bank statement or UPI app history.",
                               styles['Italic']))

    doc.build(elements)
    return output_path
